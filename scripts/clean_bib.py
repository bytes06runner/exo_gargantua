"""Make paper/refs_clean.bib from the verified paper/refs.bib for BibTeX/pdflatex: strip HTML markup returned by
publishers' content negotiation, collapse whitespace, turn Unicode punctuation and accents into LaTeX, drop
duplicate keys. Entries and identifiers are unchanged (refs.bib stays the verified source; rule 4)."""

import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PUNCT = {"‐": "-", "‑": "-", "‒": "--", "–": "--", "—": "---", "‘": "`", "’": "'",
         "“": "``", "”": "''", " ": "~", " ": " ", "−": "-", "′": "'", "×": "$\\times$",
         " ": " ", "°": "$^\\circ$", "…": "\\ldots{}"}
ACCENT = {"́": "'", "̀": "`", "̂": "^", "̈": '"', "̃": "~", "̄": "=", "̌": "v",
          "̆": "u", "̧": "c", "̊": "r", "̨": "k", "̇": "."}
SPECIAL = {"ø": "{\\o}", "Ø": "{\\O}", "ł": "{\\l}", "Ł": "{\\L}", "ß": "{\\ss}", "æ": "{\\ae}", "Æ": "{\\AE}",
           "đ": "{\\dj}", "ı": "{\\i}", "å": "{\\aa}", "Å": "{\\AA}"}


def latexify(s):
    out = []
    for ch in s:
        if ch in PUNCT:
            out.append(PUNCT[ch])
        elif ch in SPECIAL:
            out.append(SPECIAL[ch])
        elif ord(ch) < 128:
            out.append(ch)
        else:
            d = unicodedata.normalize("NFD", ch)
            base, marks = d[0], d[1:]
            if marks and all(m in ACCENT for m in marks) and ord(base) < 128:
                o = base
                for m in marks:
                    o = "{\\%s{%s}}" % (ACCENT[m], o) if ACCENT[m].isalpha() else "{\\%s%s}" % (ACCENT[m], o)
                out.append(o)
            else:
                out.append("")  # unmappable symbol: dropped (reported below)
    return "".join(out)


def main():
    text = (ROOT / "paper" / "refs.bib").read_text()
    entries = re.split(r"\n(?=@)", text)
    seen, out, dropped = set(), [], set()
    for e in entries:
        m = re.match(r"@(\w+)\{([^,]+),", e.strip())
        if not m:
            continue
        if m.group(2) in seen:
            continue
        seen.add(m.group(2))
        e = re.sub(r"</?(i|b|tt|scp|sup|sub|em|mml:[a-z]+)[^>]*>", "", e)
        e = re.sub(r"\s*\n\s*", " ", e.strip())
        dropped |= {c for c in e if ord(c) >= 128 and c not in PUNCT and c not in SPECIAL
                    and not (len(unicodedata.normalize("NFD", c)) > 1 and unicodedata.normalize("NFD", c)[0].isascii())}
        out.append(latexify(e))
    (ROOT / "paper" / "refs_clean.bib").write_text("% generated by scripts/clean_bib.py from paper/refs.bib\n\n" + "\n\n".join(out) + "\n")
    print(f"{len(out)} entries; unmappable characters dropped: {sorted(dropped)}")


if __name__ == "__main__":
    main()
